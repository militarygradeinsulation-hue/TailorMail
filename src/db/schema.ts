import {
  boolean,
  doublePrecision,
  integer,
  jsonb,
  pgTable,
  serial,
  text,
  timestamp,
} from 'drizzle-orm/pg-core';

export const businessProfiles = pgTable('business_profiles', {
  id: serial('id').primaryKey(),
  companyName: text('company_name').notNull().default(''),
  productName: text('product_name').notNull().default(''),
  valueProposition: text('value_proposition').notNull().default(''),
  targetIndustries: text('target_industries').notNull().default(''),
  idealBuyerRoles: text('ideal_buyer_roles').notNull().default(''),
  keyDifferentiators: text('key_differentiators').notNull().default(''),
  pricingSummary: text('pricing_summary').notNull().default(''),
  updatedAt: timestamp('updated_at').defaultNow(),
});

export const personas = pgTable('personas', {
  id: text('id').primaryKey(),
  name: text('name').notNull(),
  archetype: text('archetype').notNull(),
  sourceFileName: text('source_file_name').notNull(),
  rawSample: text('raw_sample').notNull(),
  cadence: text('cadence').notNull(),
  openingStyle: text('opening_style').notNull(),
  signOff: text('sign_off').notNull(),
  vocabularyTraits: jsonb('vocabulary_traits').$type<string[]>().default([]),
  updatedAt: text('updated_at').notNull(),
});

export const templates = pgTable('templates', {
  id: text('id').primaryKey(),
  title: text('title').notNull(),
  category: text('category').notNull(),
  subjectLine: text('subject_line').notNull(),
  body: text('body').notNull(),
  personaId: text('persona_id').notNull(),
  sentCount: integer('sent_count').default(0).notNull(),
  openCount: integer('open_count').default(0).notNull(),
  replyCount: integer('reply_count').default(0).notNull(),
  createdAt: timestamp('created_at').defaultNow(),
});

export const leads = pgTable('leads', {
  id: text('id').primaryKey(),
  fullName: text('full_name').notNull(),
  role: text('role').notNull(),
  company: text('company').notNull(),
  companyDomain: text('company_domain').notNull(),
  email: text('email').notNull(),
  location: text('location').notNull(),
  latitude: doublePrecision('latitude'),
  longitude: doublePrecision('longitude'),
  avatarUrl: text('avatar_url'),
  matchScore: integer('match_score').notNull().default(90),
  matchType: text('match_type').notNull().default('Web Scan'),
  buyingSignal: text('buying_signal').notNull(),
  icpFitRationale: text('icp_fit_rationale').notNull(),
  painPoints: jsonb('pain_points').$type<string[]>().default([]),
  groundingSources: jsonb('grounding_sources').$type<{ title: string; uri: string }[]>().default([]),
  status: text('status').notNull().default('Discovered'),
  cadenceMode: text('cadence_mode').notNull().default('timed_sequence'),
  timedIntervalDays: integer('timed_interval_days').notNull().default(3),
  autoHandleQuestions: boolean('auto_handle_questions').notNull().default(true),
  tailoredSubject: text('tailored_subject').notNull().default(''),
  tailoredBody: text('tailored_body').notNull().default(''),
  activeTemplateId: text('active_template_id'),
  gmailThreadId: text('gmail_thread_id'),
  followUpSteps: jsonb('follow_up_steps').$type<any[]>().default([]),
  thread: jsonb('thread').$type<any[]>().default([]),
  sentCount: integer('sent_count').notNull().default(0),
  opens: integer('opens').notNull().default(0),
  clicks: integer('clicks').notNull().default(0),
  replies: integer('replies').notNull().default(0),
  lastOpenedAt: text('last_opened_at'),
  dealValue: integer('deal_value').notNull().default(10000),
  createdAt: timestamp('created_at').defaultNow(),
});

export const invoices = pgTable('invoices', {
  id: text('id').primaryKey(),
  invoiceNumber: text('invoice_number').notNull(),
  leadId: text('lead_id').notNull().default(''),
  clientName: text('client_name').notNull(),
  company: text('company').notNull(),
  email: text('email').notNull(),
  planOrService: text('plan_or_service').notNull(),
  amount: integer('amount').notNull().default(0),
  billingCycle: text('billing_cycle').notNull().default('One-Time'),
  gateway: text('gateway').notNull().default('Stripe Express'),
  status: text('status').notNull().default('Sent'),
  issuedDate: text('issued_date').notNull(),
  dueDate: text('due_date').notNull(),
  paidAt: text('paid_at'),
  transactionRef: text('transaction_ref'),
  autoRemind: boolean('auto_remind').notNull().default(true),
  createdAt: timestamp('created_at').defaultNow(),
});

export const notifications = pgTable('notifications', {
  id: text('id').primaryKey(),
  leadId: text('lead_id').notNull().default(''),
  leadName: text('lead_name').notNull(),
  company: text('company').notNull(),
  role: text('role').notNull(),
  eventType: text('event_type').notNull(),
  summary: text('summary').notNull(),
  timestamp: text('timestamp').notNull(),
  unread: boolean('unread').notNull().default(true),
  createdAt: timestamp('created_at').defaultNow(),
});

export const teamMembers = pgTable('team_members', {
  id: text('id').primaryKey(),
  email: text('email').notNull().unique(),
  name: text('name').notNull(),
  role: text('role').notNull().default('Operator'),
  status: text('status').notNull().default('Authorized'),
  addedAt: text('added_at').notNull(),
  lastActive: text('last_active'),
  permissions: jsonb('permissions').$type<string[]>().default([
    'outbound_dispatch',
    'icp_discovery',
    'sales_qa',
    'billing',
  ]),
  createdAt: timestamp('created_at').defaultNow(),
});
